def generate_audio_markdown_reports():
    """Writes detailed Markdown guides for all audio datasets in their target directories."""
    for key, info in AUDIO_DATASET_INFO.items():
        dir_path = AUDIO_DATA_DIR / key
        dir_path.mkdir(parents=True, exist_ok=True)
        md_file = dir_path / "data_dictionary.md"
        
        content = f"# Dataset: {info['title']}\n\n"
        content += f"- **Official Homepage:** {info['official_url']}\n"
        content += f"- **Download URL:** {info['download_url']}\n"
        content += f"- **Registration Required:** {info['requires_registration']}\n"
        content += f"- **Estimated Size:** {info['file_size']}\n\n"
        content += f"## Description\n{info['description']}\n\n"
        content += f"## Expected Directory Structure\n```\n{info['folder_layout']}\n```\n\n"
        if "protocol_format" in info:
            content += f"## Protocol / Label Format\n`{info['protocol_format']}`\n\n"
            
        with open(md_file, "w", encoding="utf-8") as f:
            f.write(content)
        print(f"[OK] Created audio documentation: {md_file}")

if __name__ == "__main__":
    generate_audio_markdown_reports()
